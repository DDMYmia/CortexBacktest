"""CortexBacktest: event-driven and cross-sectional factor backtesting.

The public surface is tiered, and the tier decides how stable a name is.

**Tier 1 -- the v1 contract.** `cortexbacktest.api`, twenty-one names, versioned
by `API_VERSION`. `run_backtest` with `BacktestConfig` and `BrokerConfig` is
what a new integration should build against.

    from cortexbacktest.api import BacktestConfig, BrokerConfig, run_backtest

**Tier 2 -- the extension layer.** `BacktestEngine`, `BrokerSimulator`, custom
matching models, streaming record sinks, the research and options kernels.
Public, supported, and reachable from this root or from the subpackage that owns
it (`.event`, `.research`, `.options`, `.data`, `.datasets`, `.reporting`). Use
it for what the configuration layer cannot express; expect it to move faster
than tier 1.

This root re-exports both tiers flat, which is convenient in a notebook and says
nothing about stability. `docs/api.md` is the tier-1 contract and lists the
canonical import path of every name.
"""


